// The site's favicon (Elleta, 4 Oct 2026): the ochre E on ink, in CHIP's
// style (queue/10, option A · E). The site's brand mark, not BELLA's, so it
// is built here, not vendored (sync-bella dropped it the same day).
//
//   npm run build:favicons   writes app/icon.svg, app/icon1.png (512),
//                            app/apple-icon.png (180, full square, opaque)
//                            and app/favicon.ico (16 + 32)
//
// Colours come from tokens/bella.json: ink = color.light.ink, the E =
// color.brand.ochre. The 16px frame has its own cut: at 16 the 64-unit mark's
// E is 44% of the square and its middle bar goes soft, so the 16 cut draws a
// taller E (10 of 16 px, 62%) from whole-pixel rects. Its bars are 2px, not
// the brief's 10 units (2.5px): a 2.5px bar can't sit on whole pixels, and
// three 2px bars with 2px gaps fill the 10px height exactly. ICO packing is
// ported from BELLA's build-favicons.mjs.
import { readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const tokens = JSON.parse(readFileSync("tokens/bella.json", "utf8"));
const INK = tokens.primitive.color.light.ink.$value;
const OCHRE = tokens.primitive.color.brand.ochre.$value;

const HEADER = "<!-- Generated by scripts/build-favicons.mjs. Do not edit by hand. -->";

/* the mark, 32px and up (the brief's 64-unit drawing) */
const mark = ({ square = false } = {}) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
${HEADER}
<rect width="64" height="64"${square ? "" : ' rx="14"'} fill="${INK}"/>
<path d="M42 18 H24 V46 H42 M24 32 H38" fill="none" stroke="${OCHRE}" stroke-width="8" stroke-linecap="round" stroke-linejoin="round"/>
</svg>
`;

/* the 16px cut, drawn on the 16-pixel grid: stem and bars are whole-pixel
   rects (crisp edges); only the tile's corners are anti-aliased */
const cut16 = () => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">
${HEADER}
<rect width="16" height="16" rx="3.5" fill="${INK}"/>
<g fill="${OCHRE}" shape-rendering="crispEdges">
<rect x="4" y="3" width="2" height="10"/>
<rect x="4" y="3" width="8" height="2"/>
<rect x="4" y="7" width="7" height="2"/>
<rect x="4" y="11" width="8" height="2"/>
</g>
</svg>
`;

const raster = (svg, size) => sharp(Buffer.from(svg), { density: (72 * size) / 16 }).resize(size, size).png().toBuffer();

const svg = mark();
writeFileSync("app/icon.svg", svg);

const png16 = await raster(cut16(), 16);
const png32 = await raster(mark(), 32);
writeFileSync("app/icon1.png", await raster(mark(), 512));
/* the apple icon is opaque, square corners: iOS rounds it itself */
writeFileSync("app/apple-icon.png", await sharp(await raster(mark({ square: true }), 180)).flatten({ background: INK }).png().toBuffer());

/* favicon.ico: 16 + 32 PNG entries */
const entries = [
  { s: 16, data: png16 },
  { s: 32, data: png32 },
];
const header = Buffer.alloc(6 + 16 * entries.length);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(entries.length, 4);
let offset = header.length;
entries.forEach(({ s, data }, i) => {
  const o = 6 + i * 16;
  header.writeUInt8(s, o);
  header.writeUInt8(s, o + 1);
  header.writeUInt8(0, o + 2);
  header.writeUInt8(0, o + 3);
  header.writeUInt16LE(1, o + 4);
  header.writeUInt16LE(32, o + 6);
  header.writeUInt32LE(data.length, o + 8);
  header.writeUInt32LE(offset, o + 12);
  offset += data.length;
});
writeFileSync("app/favicon.ico", Buffer.concat([header, ...entries.map((e) => e.data)]));
console.log(`favicons: icon.svg, favicon.ico (16 cut + 32), apple-icon 180, icon1 512 (ink ${INK}, E ${OCHRE})`);
